"""Build browser-ready regular tetrahedron, cube, and octahedron meshes.

Run with: blender -b --factory-startup --python-exit-code 1 -P build_dice.py
"""
import bmesh
import json
import math
from itertools import product
from pathlib import Path
from mathutils import Vector


def convex_solid(points):
    mesh = bmesh.new()
    vertices = [mesh.verts.new(point) for point in points]
    bmesh.ops.convex_hull(mesh, input=vertices)
    bmesh.ops.dissolve_limit(mesh, angle_limit=0.001, verts=list(mesh.verts), edges=list(mesh.edges))
    mesh.verts.index_update()
    result = [tuple(vertex.co) for vertex in mesh.verts], [tuple(v.index for v in face.verts) for face in mesh.faces]
    mesh.free()
    return result


def scoring_solid(sides):
    signs = (-1, 1)
    cube = list(product(signs, repeat=3))
    if sides == 4:
        return convex_solid([p for p in cube if math.prod(p) == 1])
    if sides == 6:
        return convex_solid(cube)
    if sides == 8:
        return convex_solid([tuple(sign if index == axis else 0 for index in range(3))
                             for axis in range(3) for sign in signs])
    raise ValueError(f'Unsupported regular solid: d{sides}')


def build_die(sides):
    points, faces = scoring_solid(sides)
    points = [Vector(point) for point in points]
    radius = max(point.length for point in points)
    points = [point / radius for point in points]
    oriented = []
    for face in faces:
        a, b, c = [points[i] for i in face[:3]]
        oriented.append(face if (b - a).cross(c - a).dot(a) > 0 else face[::-1])
    assert len(oriented) == sides, sides
    return {
        'v': [[round(coordinate, 7) for coordinate in point] for point in points],
        'f': [[score, *face] for score, face in enumerate(oriented, start=1)],
    }


models = {sides: build_die(sides) for sides in (4, 6, 8)}
target = Path(__file__).resolve().parents[1] / 'public' / 'tools' / 'dice' / 'dice-meshes.js'
target.write_text(
    '// Generated by build_dice.py in Blender.\nexport const diceMeshes = '
    + json.dumps(models, separators=(',', ':')) + ';\n', encoding='utf-8')
print('Exported regular tetrahedron, cube, and octahedron dice (D4, D6, D8).')
